def _phrases(x):
    return [p for p in (x if isinstance(x, list) else [x]) if p]


def _has(text, x):
    return any(str(p).lower() in (text or "").lower() for p in _phrases(x))


def _close(a, b, tol):
    """exact for counts; abs:x and pp:x both mean |a - b| <= x in the truth's own units; pct:x is x percent of truth."""
    try:
        if tol in (None, "exact"):
            return a == b
        kind, x = tol.split(":")
        bound = abs(float(b)) * float(x) / 100 if kind == "pct" else float(x)
        return abs(float(a) - float(b)) <= bound
    except (TypeError, ValueError):
        return False


KEY_PATTERNS = {"component": r"HS[A-Z]{2}", "month": r"20\d\d-\d\d", "series": r"\b\d{4}\b", "grade": r"\d+"}


def _key(k, how=None):
    """The canonical form of a list key, so "FEMA (HSCB)" and "HSCB", or "GS-05" and "grade 5", compare equal.
    how is a KEY_PATTERNS name, "city", or {canonical: regex} tried in order; None means the trimmed text."""
    k = str(k).strip().upper()
    if isinstance(how, dict):
        return next((c for c, pat in how.items() if re.search(pat, k, re.I)), k)
    if how == "city":
        return k.split(",")[0].strip()
    m = re.search(KEY_PATTERNS[how], k) if how in KEY_PATTERNS else None
    return (str(int(m.group(0))) if how == "grade" else m.group(0)) if m else k


def _pairs(v, how=None):
    if not isinstance(v, (dict, list)):  # a bare number where a list was asked is a wrong answer, not a crash
        return []
    if isinstance(v, dict):
        return [(_key(k, how), x, None) for k, x in v.items()]
    return [(_key(i.get("key"), how), i.get("value"), i.get("rank")) for i in v or [] if isinstance(i, dict)]


LABELS = ("Verified", "Exploratory", "Not available")
WANT_LABEL = {"verified": "Verified", "genie": "Exploratory", "refusal": "Not available"}


def _label(text):
    first = (text or "").strip().splitlines()[0].strip() if (text or "").strip() else ""
    return first if first in LABELS else None


def label_match(q, row):
    return row["label"] == WANT_LABEL[q["tier"]]


def numeric_match(q, row):
    return _close(row["answer_value"], q["truth_value"], q.get("tolerance"))


def list_match(q, row):
    """A ranking passes when the answer's first N entries are truth's N in order; otherwise every truth key must be
    present with its value. Extra entries are allowed in both: listing more than asked is not a wrong answer."""
    how, tol = q.get("key_by"), q.get("tolerance")
    got, want = _pairs(row["answer_value"], how), _pairs(q["truth_value"], how)
    if any(r is not None for _, _, r in want):
        return len(got) >= len(want) and all(g[0] == w[0] and _close(g[1], w[1], tol) for g, w in zip(got, want))
    g = {k: v for k, v, _ in got}
    return all(k in g and _close(g[k], v, tol) for k, v, _ in want)


def labels_present(q, row):
    t = (row["answer_text"] or "").lower()
    return not q.get("requires_imputed_label") or any(w in t for w in ("estimated", "imputed", "approximate"))


def tool_use(q, row):
    """The expected calculations ran, and no exploratory query ran on a Verified row."""
    names = {c["name"] for c in row["tool_calls"]}
    return set(q.get("expected_tools") or []) <= names and "genie" not in names


def provenance(q, row):
    names = {c["name"] for c in row["tool_calls"]}
    return all(t in names or (t == "genie" and row["genie_sql"]) for t in row["cited_tools"])


def genie_sql_stored(q, row):
    """The SQL and its id were captured; the id is a hash of the statement text, so the row names the exact query."""
    return bool(row["genie_sql"] and row["genie_statement_id"])


def refusal(q, row):
    """Structure only: nothing retrieved, nothing asserted. Whether it declines and what it offers is limit_stated's."""
    return not any(c["result_rows"] for c in row["tool_calls"]) and row["answer_value"] is None


def data_limit(q, row):
    """Structure only: no number asserted. Whether the stated limit and nearest question are right is limit_stated's."""
    return row["answer_value"] is None


def reading_stated(q, row):
    """Truth for the first reading, and the last sentence names that reading and one alternative."""
    first, *alts = q.get("acceptable_readings") or [None]
    sentences = [x for x in re.split(r"(?<=[.!?])\s+", (row["answer_text"] or "").strip()) if x.strip()]
    last = sentences[-1] if sentences else ""
    value_ok = list_match(q, row) if isinstance(q.get("truth_value"), list) else numeric_match(q, row)
    return value_ok and _has(last, first) and any(_has(last, a) for a in alts)


